"""Regression tests for the foundational evidence and UX corrections; isolated browser harness."""
from pathlib import Path
from playwright.sync_api import sync_playwright
import json
ROOT=Path(__file__).resolve().parents[1]
HTML=(ROOT/'index.html').read_text()
checks=[]
def ok(title,yes):
    if not yes: raise AssertionError(title)
    checks.append(title)
    print('PASS',title,flush=True)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
    context=browser.new_context(viewport={'width':1366,'height':920},accept_downloads=True)
    page=context.new_page();errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.set_content(HTML,wait_until='domcontentloaded')
    page.wait_for_function('!!window.SOL_PRA_EIE_TEST')
    ok('Existing intro remains the landing experience',page.locator('.flow-opening').count()==1)
    ok('Six foundations available inside the optional EIE HUD',page.locator('[data-act=eieToggle]').count()==1)
    page.locator('[data-act=eieToggle]').click()
    ok('First foundation is visible without another navigation step',page.locator('.foundation-compass h4').inner_text().startswith('What can I do'))
    page.locator('[data-act=foundationAdvance]').click()
    ok('Advance reveals the next foundational question inline', 'What if Earth Intelligence' in page.locator('.foundation-compass h4').inner_text())
    ok('Progress HUD does not reset or navigate',page.locator('.flow-opening').count()==1)
    ok('Foundations remain explorable via accessible native disclosure',page.locator('.foundation-compass details').count()>=2)
    result=page.evaluate('window.SOL_PRA_EIE_TEST.analyze("xylophone marshmallow telescope candies")')
    ok('Irrelevant query explicitly returns no archive match',result['status']=='NO_ARCHIVE_MATCH' and result['coverage']['sourceCount']==0)
    ok('No unsupported intervention attached to irrelevant question',result['intervention'] is None)
    page.locator('#eieQuestion').fill('xylophone marshmallow telescope candies')
    page.locator('#eieForm button[type=submit]').click()
    ok('No-evidence state visibly explains the evidence gap', 'No relevant supporting source' in page.locator('.eie-output').inner_text())
    ok('No unrelated source links shown on evidence gap',page.locator('.eie-output li a').count()==0)
    page.locator('[data-act=eiePreset]').first.click()
    matched=page.evaluate('window.SOL_PRA_EIE_TEST.getResult()')
    ok('Relevant query still retrieves archival public citations',matched['status']=='ARCHIVE_MATCH' and len(matched['sources'])>=1)
    ok('Provenance coverage is labeled non-corroboration', 'Not independent corroboration' in page.locator('.eie-coverage').inner_text())
    page.locator('[data-act=eieSave]').click()
    ok('Evidence-gap work can be saved only into local notes',len(page.evaluate('window.SOL_PRA_TEST.getState().eieNotes'))==1)
    with page.expect_download() as d:page.locator('[data-act=eieExport]').click()
    draft=json.loads(Path(d.value.path()).read_text())
    ok('Draft remains private and action-disabled',draft['autonomy']=='OFF' and draft['handling']=='PRIVATE_REVIEW_DRAFT')
    ok('No unhandled JS exceptions on desktop',not errors)
    mobile=browser.new_context(viewport={'width':390,'height':844},is_mobile=True,device_scale_factor=1)
    m=mobile.new_page();m.on('pageerror',lambda e:errors.append(str(e)))
    m.set_content(HTML,wait_until='domcontentloaded');m.wait_for_function('!!window.SOL_PRA_EIE_TEST')
    m.locator('[data-act=eieToggle]').click()
    ok('Foundational question accessible in mobile HUD',m.locator('.foundation-compass').is_visible())
    m.locator('[data-act=foundationAdvance]').click()
    ok('Mobile next-question action works', 'Earth Intelligence' in m.locator('.foundation-compass h4').inner_text())
    page.locator('[data-act=eieToggle]').first.click()
    page.screenshot(path=str(ROOT/'foundations_desktop_preview.png'),full_page=True)
    m.screenshot(path=str(ROOT/'foundations_mobile_preview.png'),full_page=True)
    ok('No unhandled JavaScript exceptions on mobile',not errors)
    browser.close()
print('TOTAL',len(checks),'foundational checks')
