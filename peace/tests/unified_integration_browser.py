"""Use isolated Chromium because this execution environment blocks local HTTP/file navigation.
This validates actual DOM interactions but NOT 2-device WebRTC or hosted service workers."""
from pathlib import Path
import json
from playwright.sync_api import sync_playwright
BASE=Path(__file__).resolve().parents[1]
HTML=(BASE/'index.html').read_text()
passed=[]
def check(name,condition):
    assert condition, name
    passed.append(name); print('PASS',name,flush=True)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
    ctx=browser.new_context(viewport={'width':1440,'height':900},accept_downloads=True)
    page=ctx.new_page(); errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.set_content(HTML,wait_until='domcontentloaded');page.wait_for_function('!!window.SOL_PRA_TEST')
    api='window.SOL_PRA_TEST'
    check('Unified edition version',page.evaluate(f'{api}.VERSION')=='2.3.0')
    page.evaluate('location.hash="#/campaign"');page.wait_for_function('document.querySelector(".world-banner") !== null')
    check('All five node datasets embedded',page.evaluate(f'Object.keys({api}.ARCHIVE).length')==5)
    check('Original route registry intact',page.evaluate(f'{api}.ROUTES.length')>=12)
    check('Native campaign rendered',page.locator('.world-banner').count()==1)
    check('Five interactive domain orbs',page.locator('.node-orb').count()==5)
    check('Daily status labeled as archive','CONVERGENCE WORLDS' in page.locator('.world-banner').inner_text().upper())
    check('Progressive foundation available through HUD',page.locator('[data-act=eieToggle]').count()==1)
    check('Persistent learner HUD preserved',page.locator('#journeyHud').count()==1)
    check('Comparative analysis panel rendered',page.locator('#compareResults .split').count()==1)
    page.locator('[data-act="focusMission"][data-id="fbi"]').click()
    check('Switch discipline without changing route', 'FBI' in page.locator('#missionFocus').inner_text() and page.evaluate('location.hash')=='#/campaign')
    check('Domain orb updates aria-pressed',page.locator('[data-act="focusMission"][data-id="fbi"]').get_attribute('aria-pressed')=='true')
    page.locator('#compareA').select_option('fbi');page.locator('#compareB').select_option('cia')
    check('Comparison updates inline', 'FBI' in page.locator('#compareResults').inner_text() and 'CIA' in page.locator('#compareResults').inner_text())
    page.locator('a[href="#/atlas"]').first.click()
    page.wait_for_function('document.querySelector("#atlasResults") && location.hash === "#/atlas"')
    check('Atlas reachable by integrated control',page.evaluate('location.hash')=='#/atlas')
    check('Atlas displays 19 total case records',page.locator('article.native-card').count()==19)
    page.locator('#atlasType').select_option('sources')
    check('Atlas loads source data with pagination',page.locator('article.native-card').count()==24)
    page.locator('[data-act="moreAtlas"]').click()
    check('Atlas pagination reveals additional records',page.locator('article.native-card').count()==48)
    page.locator('#atlasNode').select_option('un')
    check('Atlas filters to UN sources',page.locator('article.native-card').count()==20)
    page.locator('#atlasType').select_option('actions')
    check('Atlas limits to UN intervention records',page.locator('article.native-card').count()==9)
    page.locator('article.native-card details summary').first.click()
    check('Record opens inline without a modal',page.locator('article.native-card details[open]').count()==1 and page.locator('dialog').count()==0)
    page.locator('#atlasQuery').fill('civilian')
    check('Atlas keyword filter reacts to text input',page.locator('article.native-card').count()>=1)
    page.locator('#atlasQuery').fill('q_unmatched_text_zzzz')
    check('Atlas handles no matches',page.locator('article.native-card').count()==0)
    page.locator('#atlasQuery').fill('')
    page.locator('#atlasNode').select_option('all');page.locator('#atlasType').select_option('actions')
    check('Atlas totals 37 proposed actions', '37' in page.locator('#atlasResults').inner_text())
    check('Outlink to packaged edition exists',page.locator('a[href="./usmc/index.html"]').count()>0)
    page.locator('a[href="#/overview"]').first.click()
    page.wait_for_function('document.querySelector(".flow-surface") !== null')
    check('Returning to integrated flow works',page.locator('.flow-surface').count()==1)
    page.evaluate('location.hash="#/guilds"');page.wait_for_function('document.querySelector(".class-pick") !== null')
    page.locator('.class-pick[data-class="cartographer"]').click()
    check('Changing class still local',page.evaluate(f'{api}.getState().profile.classId')=='cartographer')
    # Confirm native source security posture
    check('All corpus source links use HTTPS',page.evaluate('Object.values(window.SOL_PRA_TEST.ARCHIVE).every(n=>(n.sources||[]).every(s=>!s.url||s.url.startsWith("https://")))'))
    with page.expect_download() as d:page.locator('#backupBtn').click()
    backup=json.loads(Path(d.value.path()).read_text())
    check('Original backup schema preserved',backup['schema']=='pra.sol_peace_master' and backup['version']==1)
    check('No JS page exceptions',not errors)
    page.screenshot(path=str(BASE/'desktop_preview.png'),full_page=True)
    # Capture atlas screenshot separately
    page.evaluate('location.hash="#/atlas"');page.wait_for_timeout(200)
    page.screenshot(path=str(BASE/'atlas_preview.png'),full_page=True)
    mobile=browser.new_context(viewport={'width':393,'height':852},device_scale_factor=1,is_mobile=True,has_touch=True)
    mp=mobile.new_page();mp.on('pageerror',lambda e:errors.append(str(e)));mp.set_content(HTML,wait_until='domcontentloaded');mp.wait_for_function('!!window.SOL_PRA_TEST')
    mp.evaluate('location.hash="#/campaign"');mp.wait_for_function('document.querySelector(".node-orb") !== null')
    check('Mobile campaign uses five node controls',mp.locator('.node-orb').count()==5)
    mp.locator('[data-act="focusMission"][data-id="cia"]').click()
    check('Mobile inline node switching functional','CIA' in mp.locator('#missionFocus').inner_text())
    mp.locator('#menuBtn').click()
    check('Mobile drawer opens',mp.locator('#sidebar').evaluate('(el)=>el.classList.contains("open")'))
    mp.keyboard.press('Escape')
    check('Mobile drawer escapes',not mp.locator('#sidebar').evaluate('(el)=>el.classList.contains("open")'))
    mp.screenshot(path=str(BASE/'mobile_preview.png'),full_page=True)
    check('No mobile JS exceptions',not errors)
    browser.close()
print('TOTAL',len(passed),'unified browser checks')
