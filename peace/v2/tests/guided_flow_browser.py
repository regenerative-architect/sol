from pathlib import Path
from playwright.sync_api import sync_playwright
import json
BASE=Path(__file__).resolve().parents[1]
HTML=(BASE/'index.html').read_text()
passed=[]; errors=[]
def check(label,condition):
 assert condition,label
 passed.append(label); print('PASS',label,flush=True)
with sync_playwright() as p:
 b=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
 c=b.new_context(viewport={'width':1400,'height':900},accept_downloads=True)
 pg=c.new_page();pg.on('pageerror',lambda e:errors.append(str(e)));pg.set_content(HTML,wait_until='domcontentloaded');pg.wait_for_function('!!window.SOL_PRA_TEST')
 check('HUD renders level, XP, quests, skill points','0 XP' in pg.locator('#journeyHud').inner_text() and 'Quests' in pg.locator('#journeyHud').inner_text())
 check('Fifth phase tiles in overview',pg.locator('.journey-step').count()==5)
 check('Eight accessible inline class selections',pg.locator('.class-pick').count()==8)
 check('No blocking dialog in guided overview',pg.locator('dialog').count()==0)
 check('A collapsible inline pro tip is present',pg.locator('details.protip').count()>=2)
 pg.locator('.protip summary').first.click()
 check('Pro-tip clue reveals in place',pg.locator('.protip').first.evaluate('(el)=>el.open'))
 pg.locator('.class-pick[data-class="steward"]').click()
 check('Changing class does not navigate',pg.evaluate('window.SOL_PRA_TEST.getState().profile.classId')=='steward' and pg.evaluate('location.hash') in ('','#/overview'))
 pg.locator('[data-act="nextStage"]').first.click()
 check('Phase 2 unfolds inline',pg.evaluate('window.SOL_PRA_TEST.getJourneyStage()')==1 and pg.locator('.journey-step[data-active="true"][data-stage="1"]').count()==1)
 qid=pg.locator('.journey-step[data-stage="1"] [data-act="questDetail"]').first.get_attribute('data-id')
 pg.locator('.journey-step[data-stage="1"] [data-act="questDetail"]').first.click()
 check('Quest proof expands inline not modal',pg.locator('#questModal').count()==1 and pg.locator('dialog').count()==0)
 pg.locator('#questSource').fill('https://www.un.org/en/')
 pg.locator('#questProof').fill('Reviewed a dated primary public report, identified uncertainty and wrote a human-verifiable civilian indicator.')
 pg.locator('#claimQuest').click()
 check('Quest XP stored and HUD updates',pg.evaluate('(id)=>!!window.SOL_PRA_TEST.getState().completed[id]',qid) and int(pg.evaluate('window.SOL_PRA_TEST.QUESTS.find(q=>q.id==='+json.dumps(qid)+').xp')) > 0)
 pg.locator('.expedition-steps [data-step="2"]').click()
 check('Skill guidance appears',pg.locator('.journey-step[data-active="true"] .mini-meter').count()==1)
 pg.locator('.expedition-steps [data-step="3"]').click()
 check('Touch friendly discipline checkboxes in project step',pg.locator('#quickProjectForm input[name="quickNode"]').count()==5)
 pg.locator('#quickTitle').fill('Civilian winter infrastructure evidence ledger')
 pg.locator('#quickSource').fill('https://www.un.org/en/')
 pg.locator('#quickSummary').fill('Study a public civilian infrastructure resilience indicator with explicit permission boundaries, independent evidence and a stop rule.')
 pg.locator('#quickProjectForm button[type="submit"]').click()
 check('Quick proposal saved, phase 5 opens',pg.evaluate('window.SOL_PRA_TEST.getState().projects.length')==1 and pg.evaluate('window.SOL_PRA_TEST.getJourneyStage()')==4)
 check('Private JSON and public handoff available without peer connection',pg.locator('.journey-step[data-stage="4"] [data-act="exportBackup"]').count()==1 and pg.locator('.journey-step[data-stage="4"] [data-act="projectHandoff"]').count()==1)
 with pg.expect_download() as dl:pg.locator('.journey-step[data-stage="4"] [data-act="projectHandoff"]').click()
 obj=json.loads(Path(dl.value.path()).read_text())
 check('Quick-project export is public only and unsigned',obj['handling']=='PUBLIC_ONLY' and obj['authenticity']=='UNSIGNED_LOCAL_DRAFT')
 pg.locator('[data-act="toggleMotion"]').click()
 check('Animation can be disabled',pg.locator('html').get_attribute('data-motion')=='off')
 pg.locator('[data-act="toggleMotion"]').click()
 check('Animation can be re-enabled',pg.locator('html').get_attribute('data-motion')=='on')
 check('No JavaScript page errors',not errors)
 pg.screenshot(path=str(BASE/'desktop_preview.png'),full_page=True)
 m=b.new_context(viewport={'width':393,'height':852},is_mobile=True,has_touch=True,accept_downloads=True)
 mp=m.new_page();mp.on('pageerror',lambda e:errors.append(str(e)));mp.set_content(HTML,wait_until='domcontentloaded');mp.wait_for_function('!!window.SOL_PRA_TEST')
 check('Mobile overview stays compact',mp.locator('.journey-hud').count()==1 and mp.locator('.journey-step').count()==5)
 # test mobile progress without drawer usage
 mp.locator('.journey-step[data-stage="0"] [data-act="nextStage"]').click()
 check('Mobile advances without opening navigation drawer',mp.evaluate('window.SOL_PRA_TEST.getJourneyStage()')==1 and not mp.locator('#sidebar').evaluate('(el)=>el.classList.contains("open")'))
 mp.screenshot(path=str(BASE/'mobile_preview.png'),full_page=True)
 check('No new mobile JS errors',not errors)
 b.close()
print('GUIDED PASS',len(passed),'checks')
