from pathlib import Path
from playwright.sync_api import sync_playwright
import json
BASE=Path(__file__).resolve().parents[1]; html=(BASE/'index.html').read_text()
checks=[]
def ok(name,expr):
    if not expr:raise AssertionError(name)
    checks.append(name); print('PASS',name,flush=True)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
    context=browser.new_context(viewport={'width':1440,'height':900},accept_downloads=True)
    page=context.new_page(); errs=[];page.on('pageerror',lambda e:errs.append(str(e)))
    page.set_content(html,wait_until='domcontentloaded');page.wait_for_function('window.SOL_PRA_FLOW_TEST !== undefined')
    ok('New introduction is the home route',page.locator('.flow-opening h1').count()==1)
    ok('All original routes retained',page.evaluate('window.SOL_PRA_TEST.ROUTES.length')>=12)
    ok('No mandatory selection on welcome',page.locator('.flow-opening .class-picks').count()==0)
    ok('Full research data embedded',page.evaluate('Object.keys(window.SOL_PRA_TEST.ARCHIVE).length')==5)
    ok('Advanced navigation collapsed on desktop',page.locator('#sidebar').evaluate('(x)=>getComputedStyle(x).transform!=="none"'))
    page.locator('#menuBtn').click()
    ok('Research menu opens only on demand',page.locator('#sidebar').evaluate('(x)=>x.classList.contains("open")'))
    page.keyboard.press('Escape')
    ok('Escape closes menu',not page.locator('#sidebar').evaluate('(x)=>x.classList.contains("open")'))
    page.locator('[data-act="flowNext"]').click()
    ok('Seamless switch to source view',page.locator('.flow-pane h2').inner_text()=='Start with what we can check.')
    ok('Step indicator becomes visible',page.locator('#flowTrail').is_visible())
    page.locator('#flowScene details summary').first.click();page.locator('[data-act="flowDomain"][data-id="fbi"]').click()
    ok('Research perspective changes inline',page.evaluate('window.SOL_PRA_FLOW_TEST.getDomain()')=='fbi')
    ok('Change perspective preserves route',page.evaluate('location.hash') in ('','#/overview'))
    page.locator('[data-act="flowNext"]').click()
    ok('Reflection available without modal',page.locator('form#flowEvidenceForm').count()==1 and page.locator('dialog').count()==0)
    page.locator('#flowEvidenceNote').fill('This source defines an agency role, but cannot independently prove a specific shipment.')
    page.locator('#flowEvidenceForm button[type=submit]').click()
    ok('Learning saved and moves to build view',page.locator('form#flowProjectForm').count()==1)
    ok('Self-reported learning XP awarded',page.evaluate('window.SOL_PRA_TEST.getState().completed.q04 !== undefined'))
    page.locator('#flowProjectTitle').fill('Public evidence verification brief')
    page.locator('#flowProjectSummary').fill('Review one public-source discrepancy with an independent second reference; stop attribution if the model or facts cannot be corroborated.')
    page.locator('#flowProjectForm button[type=submit]').click()
    ok('Project save flows into optional continuation',page.locator('.flow-pane h2').inner_text()=='Your work remains yours.')
    ok('Project draft is kept private',page.evaluate('window.SOL_PRA_TEST.getState().projects.length')==1)
    with page.expect_download() as d:page.locator('#flowScene [data-act="exportBackup"]').click()
    backup=json.loads(Path(d.value.path()).read_text())
    ok('Backup format remains backward-compatible',backup['schema']=='pra.sol_peace_master' and backup['version']==1)
    page.locator('[data-act="flowLoop"]').click()
    ok('Revisit source without resetting work',page.locator('.flow-pane h2').inner_text()=='Start with what we can check.' and page.evaluate('window.SOL_PRA_TEST.getState().projects.length')==1)
    page.locator('.flow-bottom a[href="#/atlas"]').click()
    page.wait_for_function('location.hash === "#/atlas" && document.querySelector("#atlasResults") !== null',timeout=10000);ok('Advanced Atlas still works',page.locator('#atlasResults').count()==1)
    page.locator('.brand[href="#/overview"]').click()
    page.wait_for_function('location.hash === "#/overview" && document.querySelector(".flow-surface") !== null',timeout=10000);ok('Return to flow works',page.locator('.flow-surface').count()==1)
    ok('No JavaScript errors desktop',not errs)
    page.evaluate('window.SOL_PRA_FLOW_TEST.flowSetStep(0)')
    page.screenshot(path=str(BASE/'desktop_preview.png'),full_page=True)
    mc=browser.new_context(viewport={'width':393,'height':852},device_scale_factor=1,is_mobile=True,has_touch=True)
    mp=mc.new_page();mp.on('pageerror',lambda e:errs.append(str(e)));mp.set_content(html,wait_until='domcontentloaded');mp.wait_for_function('!!window.SOL_PRA_FLOW_TEST')
    ok('Mobile introduction loads',mp.locator('.flow-opening h1').count()==1)
    mp.locator('[data-act="flowNext"]').click()
    ok('Mobile first transition works',mp.locator('.flow-pane h2').inner_text()=='Start with what we can check.')
    mp.locator('[data-act="flowNext"]').click()
    ok('Mobile reflection can be skipped',mp.locator('#flowEvidenceForm').count()==1)
    mp.locator('[data-act="flowNext"]').click()
    ok('Mobile action proposal available',mp.locator('#flowProjectForm').count()==1)
    mp.locator('[data-act="flowNext"]').click()
    ok('Mobile full path reachable without sidebar',mp.locator('.flow-pane h2').inner_text()=='Your work remains yours.')
    mp.locator('#menuBtn').click()
    ok('Mobile drawer works',mp.locator('#sidebar').evaluate('(x)=>x.classList.contains("open")'))
    mp.keyboard.press('Escape')
    ok('Mobile drawer closes on Escape',not mp.locator('#sidebar').evaluate('(x)=>x.classList.contains("open")'))
    mp.evaluate('window.SOL_PRA_FLOW_TEST.flowSetStep(0)')
    mp.screenshot(path=str(BASE/'mobile_preview.png'),full_page=True)
    ok('No JavaScript errors mobile',not errs)
    browser.close()
print('TOTAL',len(checks),'checks')
