from pathlib import Path
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[1]
HTML=(ROOT/'index.html').read_text()
checks=[]
def ck(label,ok):
 if not ok: raise AssertionError(label)
 print('PASS',label,flush=True);checks.append(label)
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
 for mobile in [False, True]:
  ctx=browser.new_context(viewport={'width':390 if mobile else 1440,'height':780 if mobile else 960},is_mobile=mobile)
  page=ctx.new_page();errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
  page.set_content(HTML,wait_until='domcontentloaded')
  page.wait_for_function('window.SOL_PRA_EIE_TEST && document.querySelector(".eie-hud-toggle")')
  tag='mobile' if mobile else 'desktop'
  ck(tag+' banner starts visible',not page.locator('.eie-hud-toggle').evaluate('(e)=>e.classList.contains("is-compact")'))
  ck(tag+' initial text label',page.locator('.eie-hud-toggle .eie-title').inner_text()=='Earth Intelligence')
  page.wait_for_function('document.querySelector(".eie-hud-toggle")?.classList.contains("is-compact")',timeout=5500)
  btn=page.locator('.eie-hud-toggle')
  ck(tag+' icon auto-minimizes',page.evaluate('window.SOL_PRA_EIE_TEST.getEieCompact()'))
  ck(tag+' compact width ~44px',btn.bounding_box()['width']<=48)
  page.wait_for_function('parseFloat(getComputedStyle(document.querySelector(".eie-hud-toggle .eie-title")).opacity)<.01',timeout=3000)
  ck(tag+' compact title visually hidden',btn.locator('.eie-title').evaluate('(e)=>parseFloat(getComputedStyle(e).opacity)<.01'))
  ck(tag+' tooltip/accessible label present',btn.get_attribute('aria-label')=='Open Earth Intelligence Engine' and 'Open Earth Intelligence' in btn.get_attribute('title'))
  ck(tag+' collapsed panel absent',page.locator('#earthEngine').count()==0)
  btn.click()
  ck(tag+' EIE panel opens',page.locator('#earthEngine').is_visible())
  ck(tag+' icon stays compact and shows close',page.locator('.eie-hud-toggle').bounding_box()['width']<=48 and page.locator('.eie-hud-toggle .eie-pulse').inner_text()=='×')
  ck(tag+' focus enters EIE input',page.evaluate('document.activeElement?.id')=='eieQuestion')
  page.locator('#eieQuestion').fill('civilian protection evidence')
  page.locator('#eieForm button[type=submit]').click()
  ck(tag+' EIE analysis preserved',page.locator('#earthEngine').is_visible())
  page.locator('.eie-hud-toggle').click()
  ck(tag+' button collapses EIE',page.locator('#earthEngine').count()==0 and page.locator('.eie-hud-toggle').get_attribute('aria-expanded')=='false')
  page.wait_for_function('document.activeElement?.classList.contains("eie-hud-toggle")===true',timeout=3000)
  ck(tag+' focus returns to HUD icon',page.evaluate('document.activeElement?.classList.contains("eie-hud-toggle")')==True)
  page.evaluate('window.SOL_PRA_TEST.render()')
  ck(tag+' compact state survives HUD render',page.locator('.eie-hud-toggle').bounding_box()['width']<=48)
  ck(tag+' no horizontal overflow',page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
  ck(tag+' no browser exceptions',not errors)
  page.wait_for_timeout(450)
  page.screenshot(path=str(ROOT/('eie_compact_mobile.png' if mobile else 'eie_compact_desktop.png')),full_page=False)
  ctx.close()
 # Accessibility: icon must be operable without mouse.
 ctx=browser.new_context(viewport={'width':1024,'height':768},reduced_motion='reduce')
 page=ctx.new_page(); page.set_content(HTML,wait_until='domcontentloaded')
 page.wait_for_function('document.querySelector(".eie-hud-toggle")?.classList.contains("is-compact")',timeout=3000)
 ck('reduced-motion loads directly minimized',page.locator('.eie-hud-toggle').bounding_box()['width']<=48)
 page.locator('.eie-hud-toggle').focus();page.keyboard.press('Enter')
 ck('keyboard Enter opens EIE',page.locator('#earthEngine').is_visible())
 page.locator('.eie-hud-toggle').focus();page.keyboard.press('Space')
 ck('keyboard Space collapses EIE',page.locator('#earthEngine').count()==0)
 ctx.close()
 browser.close()
print('TOTAL',len(checks))
